/**
 * Returns merged brands combining curated list with dynamic user-registered brands from product store.
 */
export function getMergedBrands(userCustomBrands: string[] = []): string[] {
  const brandSet = new Set<string>();

  // Add all static curated brands
  for (const b of CURATED_BRANDS) {
    const trimmed = b.trim();
    if (trimmed) brandSet.add(trimmed);
  }

  // Add dynamic custom brands registered by players
  for (const b of userCustomBrands) {
    const trimmed = String(b || '').trim();
    if (trimmed && trimmed.toLowerCase() !== 'others' && trimmed.toLowerCase() !== 'other') {
      brandSet.add(trimmed);
    }
  }

  return Array.from(brandSet).sort((a, b) => a.localeCompare(b, undefined, { sensitivity: 'base' }));
}
